export function developerTr(language: Language, value: string) {
  return language === "de" ? text[value] || value : value
}

export function developerSectionLabel(language: Language, sectionName: string) {
  return serviceSectionLabel(language, sectionName)
}

export function buildDeveloperSourceExcerptLabel(language: Language, sectionName?: string) {
  const baseLabel = developerTr(language, "Source excerpt")
  if (!sectionName) return baseLabel
  return `${baseLabel} · ${developerSectionLabel(language, sectionName)}`
}

export function formatNumber(value: number | undefined) {
  if (typeof value !== "number") return "-"
  return value.toFixed(3).replace(/0+$/, "").replace(/\.$/, "")
}

export function reviewDecisionLabel(language: Language, value: string | undefined) {
  const normalized = value || ""
  return (developerTr(language, normalized) || normalized).replaceAll("_", " ") || "-"
}
